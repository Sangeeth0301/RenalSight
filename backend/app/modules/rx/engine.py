"""Rx engine: care plan, draft medicine suggestions and deterministic safety checks.

No AI is involved here. All thresholds come from rules.json and must be reviewed by a doctor / pharmacist.
Messages carry a stable `code` so the frontend can show fixed, native-speaker-reviewed translations (en/ta/bn/te);
`text_en` is the English fallback.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

RULES = Path(__file__).with_name("rules.json")
RAAS = {"ace_inhibitor", "arb"}
DISCLAIMER = "Draft generated by software for a doctor to review. It is not valid until signed by a doctor."


@lru_cache
def rules() -> dict:
    return json.loads(RULES.read_text(encoding="utf-8"))


def drug(key: str) -> dict | None:
    return rules()["formulary"].get(key)


# =================================================================== care plan
def _item(code, text, **params):
    return {"code": code, "text_en": text, "params": params}


def care_plan(s: dict) -> dict:
    """Lifestyle and monitoring plan from the patient snapshot. Safe for patients to read (no drug doses)."""
    egfr, acr, k = s.get("egfr"), s.get("acr"), s.get("potassium")
    g = s.get("g_stage")
    a = s.get("a_category") or "A1"
    sec: dict[str, list] = {"urgent": [], "diet": [], "fluids": [], "blood_pressure": [], "blood_sugar": [], "medicines": [], "activity": [], "monitoring": [], "warning_signs": []}

    if egfr is not None and egfr < 15:
        sec["urgent"].append(_item("urgent_stage5", "Your kidney function is in the kidney-failure range. Please contact your doctor or the nearest hospital today."))
    if k is not None and k >= 6.0:
        sec["urgent"].append(_item("urgent_potassium", "Your potassium is very high. This can affect the heart. Please contact a doctor today.", potassium=k))
    if s.get("sbp") is not None and s["sbp"] >= 180:
        sec["urgent"].append(_item("urgent_bp", "Your blood pressure is very high. Please contact a doctor today.", sbp=s["sbp"]))

    sec["diet"].append(_item("diet_salt", "Keep salt low: under 5 g of salt (about 1 teaspoon) a day. Avoid pickles, papad, salted snacks, instant noodles and salted fish."))
    if g in ("G3a", "G3b", "G4", "G5"):
        sec["diet"].append(_item("diet_protein", "Do not eat extra protein. About 0.8 g of protein per kg of body weight per day is usual; your doctor or dietitian will tell you the right amount."))
    if k is not None and k >= 5.0:
        sec["diet"].append(_item("diet_potassium_high", "Your potassium is high. Limit bananas, tender coconut water, potatoes, tomatoes and leafy-green curries until your doctor says otherwise.", potassium=k))
    if g in ("G4", "G5"):
        sec["diet"].append(_item("diet_phosphate", "Limit processed foods, colas and packaged snacks (hidden phosphate). Ask your doctor about phosphate tests."))
    sec["fluids"].append(_item("fluids_general", "Drink water normally unless your doctor has asked you to limit fluids. Do not drink large amounts to 'flush' the kidneys."))
    if g in ("G4", "G5"):
        sec["fluids"].append(_item("fluids_ask", "In advanced kidney disease your doctor may set a daily fluid limit. Ask at your next visit."))

    sec["blood_pressure"].append(_item("bp_target", "Check your blood pressure regularly. A usual goal for people with CKD is below 130/80; your doctor will set your target."))
    if s.get("diabetes"):
        sec["blood_sugar"].append(_item("sugar_target", "Keep blood sugar controlled. HbA1c around 7% is a common goal; your doctor will set yours."))
    sec["medicines"].append(_item("avoid_nsaids", "Do not take pain-killers such as ibuprofen, diclofenac or naproxen. They can harm the kidneys. Ask a doctor or pharmacist for a safe alternative."))
    sec["medicines"].append(_item("avoid_herbal", "Tell your doctor about all herbal, ayurvedic or traditional medicines. Some can harm the kidneys."))
    sec["medicines"].append(_item("sick_day", "If you have vomiting or diarrhoea, call your doctor: some medicines may need to be paused for a short time."))
    sec["activity"].append(_item("activity_walk", "Walk or do light exercise most days (about 150 minutes a week) as your doctor allows."))
    sec["activity"].append(_item("no_tobacco", "Do not smoke or chew tobacco."))

    per_year = None
    if g in rules()["kdigo_monitoring_per_year"]:
        per_year = rules()["kdigo_monitoring_per_year"][g].get(a if a in ("A1", "A2", "A3") else "A1")
        sec["monitoring"].append(_item("monitor_frequency", f"You should have kidney blood and urine tests about {per_year} time(s) a year.", per_year=per_year))
    sec["monitoring"].append(_item("monitor_home", "Write down your blood pressure and weight. Bring all reports to each visit."))

    for code, txt in (("warn_swelling", "swelling of the feet, legs or face"), ("warn_breath", "breathlessness"),
                      ("warn_urine", "passing much less urine than usual"), ("warn_vomit", "continuous vomiting or severe weakness"),
                      ("warn_chest", "chest pain or a very slow or irregular heartbeat")):
        sec["warning_signs"].append(_item(code, f"Go to a doctor urgently if you have {txt}."))
    return {"stage": g, "a_category": a if s.get("acr") is not None else None, "sections": sec, "disclaimer": DISCLAIMER}


# =================================================================== draft suggestions
def suggest_items(s: dict) -> list[dict]:
    """Medicine ideas for the DOCTOR to consider, based on KDIGO-style indications. Never shown with doses to patients."""
    out = []
    egfr, acr, k, sbp = s.get("egfr"), s.get("acr"), s.get("potassium"), s.get("sbp")
    age = s.get("age") or 0
    raas_ok = k is None or k < rules()["potassium_warn"]
    htn = bool(s.get("hypertension")) or (sbp is not None and sbp >= 130)
    albuminuric = acr is not None and acr >= 30
    if raas_ok and (albuminuric and (s.get("diabetes") or htn) or (htn and egfr is not None and egfr < 60)):
        key = "losartan"
        t = drug(key)["typical"]
        out.append(_sug(key, t, "Albuminuria or hypertension with CKD: RAAS blocker is recommended; start low and check potassium and creatinine in 1-2 weeks."))
    if egfr is not None and egfr >= 20 and (s.get("diabetes") or (albuminuric and acr >= 200) or egfr < 45):
        t = drug("dapagliflozin")["typical"]
        out.append(_sug("dapagliflozin", t, "SGLT2 inhibitors slow CKD progression (diabetes, albuminuria or eGFR 20-45)."))
    if age >= 50 or (s.get("diabetes") and age >= 40):
        out.append(_sug("atorvastatin", drug("atorvastatin")["typical"], "Statin recommended for adults 50+ with CKD (or diabetes 40+)."))
    if sbp is not None and sbp >= 140 and any(o["drug_key"] == "losartan" for o in out):
        out.append(_sug("amlodipine", drug("amlodipine")["typical"], "Blood pressure still high on the first agent: consider adding a second drug."))
    return out


def _sug(key, typical, reason):
    d = drug(key)
    return {"drug_key": key, "drug_name": d["name"], "dose_mg": typical["dose_mg"], "times_per_day": typical["times_per_day"],
            "duration_days": None, "instructions": d.get("monitor") or None, "reason": reason, "suggested_by_system": True}


# =================================================================== safety check
def _w(severity, code, text, drug_key=None):
    return {"severity": severity, "code": code, "text_en": text, "drug": drug_key}


def safety_check(s: dict, items: list[dict]) -> dict:
    """Deterministic checks. severity: block (cannot sign without a written override), warn, info."""
    R = rules()
    egfr, k = s.get("egfr"), s.get("potassium")
    warnings: list[dict] = []
    drugs = []
    for it in items:
        d = drug(it["drug_key"])
        if d is None:
            warnings.append(_w("warn", "unknown_drug", f"'{it['drug_key']}' is not in the rule file, so it could not be checked.", it["drug_key"]))
            continue
        drugs.append((it, d))
    classes = [d["class"] for _, d in drugs]

    if egfr is None and drugs:
        warnings.append(_w("block", "no_egfr", "No eGFR is available for this patient, so renal dosing cannot be checked."))

    for it, d in drugs:
        key, cls = it["drug_key"], d["class"]
        daily = None if it.get("dose_mg") is None or it.get("times_per_day") is None else it["dose_mg"] * it["times_per_day"]
        if it.get("dose_mg") is None or it.get("times_per_day") is None:
            warnings.append(_w("warn", "dose_missing", f"{d['name']}: dose or frequency is missing.", key))
        if daily is not None:
            limit = d.get("max_mg_day")
            for band in d.get("renal_max", []):
                if egfr is not None and egfr < band["egfr_lt"]:
                    limit = band["max_mg_day"] if limit is None else min(limit, band["max_mg_day"])
            if limit is not None and daily > limit:
                why = "at this eGFR" if limit != d.get("max_mg_day") else ""
                warnings.append(_w("warn", "dose_above_max", f"{d['name']}: {daily:g} mg/day is above the usual maximum of {limit:g} mg/day {why}".strip(), key))
        if cls == "nsaid":
            sev = "block" if (egfr is None or egfr < 60) else "warn"
            warnings.append(_w(sev, "nsaid_ckd", f"{d['name']} (NSAID) can worsen kidney function and is usually avoided in CKD.", key))
        if key == "metformin" and egfr is not None:
            if egfr < d["contraindicated_egfr_lt"]:
                warnings.append(_w("block", "metformin_contra", "Metformin is contraindicated when eGFR is below 30.", key))
            elif egfr < 45:
                warnings.append(_w("warn", "metformin_review", "eGFR is below 45: do not start metformin; reduce dose and review if already on it.", key))
        if cls == "sglt2" and egfr is not None and egfr < d["min_egfr_start"]:
            warnings.append(_w("warn", "sglt2_low_egfr", f"{d['name']}: starting is not recommended when eGFR is below {d['min_egfr_start']}; continuing may be reasonable.", key))
        if cls in RAAS | {"mra", "potassium_supplement"} and k is not None:
            if k >= R["potassium_block"]:
                warnings.append(_w("block", "potassium_very_high", f"Potassium is {k:g} mmol/L (6.0 or more): {d['name']} can raise it further.", key))
            elif k >= R["potassium_warn"]:
                warnings.append(_w("warn", "potassium_high", f"Potassium is {k:g} mmol/L: use {d['name']} with great caution and recheck soon.", key))
        if cls in RAAS or cls == "sglt2":
            if s.get("sex") == "female" and s.get("age") is not None and 15 <= s["age"] <= 49:
                warnings.append(_w("warn", "pregnancy", f"{d['name']}: confirm the patient is not pregnant or planning pregnancy.", key))
        if d.get("monitor") and cls in RAAS | {"mra", "sglt2"}:
            warnings.append(_w("info", "monitoring", f"{d['name']}: {d['monitor']}", key))

    if "ace_inhibitor" in classes and "arb" in classes:
        warnings.append(_w("block", "dual_raas", "An ACE inhibitor and an ARB together (dual RAAS blockade) increase the risk of kidney injury and high potassium."))
    if (RAAS & set(classes)) and "mra" in classes:
        warnings.append(_w("warn", "raas_mra", "RAAS blocker plus spironolactone: high risk of high potassium. Monitor closely."))
    if (RAAS & set(classes)) and "nsaid" in classes and "loop_diuretic" in classes:
        warnings.append(_w("block", "triple_whammy", "RAAS blocker + diuretic + NSAID ('triple whammy') carries a high risk of acute kidney injury."))
    for cls in set(classes):
        if classes.count(cls) > 1 and cls not in ("nsaid",):
            warnings.append(_w("warn", "duplicate_class", f"Two medicines of the same class ({cls.replace('_', ' ')}) are listed."))

    order = {"block": 0, "warn": 1, "info": 2}
    warnings.sort(key=lambda w: order[w["severity"]])
    blocks = sum(w["severity"] == "block" for w in warnings)
    return {"ok_to_sign": blocks == 0, "blocking": blocks, "warnings": warnings, "checked_items": len(items), "egfr_used": egfr,
            "note": "Rules are drawn from public guidance and need doctor/pharmacist review. This check does not replace clinical judgement."}
