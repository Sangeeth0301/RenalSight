"""Prescription as a PDF (English, ReportLab) and as printable HTML (any language the browser has fonts for).

Complex Indian scripts cannot be shaped by ReportLab; for Tamil / Bengali / Telugu the frontend should open the
HTML version (/rx/{id}/print) and use the browser's Save-as-PDF, which renders the scripts correctly.
"""
from html import escape
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def _lines(p, patient, doctor, items):
    rows = []
    for i in items:
        dose = "-" if i.dose_mg is None else f"{i.dose_mg:g} mg x {i.times_per_day:g}/day" if i.times_per_day else f"{i.dose_mg:g} mg"
        dur = "as directed" if not i.duration_days else f"{i.duration_days} days"
        rows.append((i.drug_name, dose, dur, i.instructions or ""))
    return rows


def build_pdf(p, patient, doctor, items) -> bytes:
    ss = getSampleStyleSheet()
    B = ParagraphStyle("b", parent=ss["BodyText"], fontSize=10, leading=14)
    teal = colors.HexColor("#0d9488")
    buf = BytesIO()
    signed = p.status == "signed"

    def mark(c, doc):
        if not signed:
            c.saveState()
            c.setFont("Helvetica-Bold", 60)
            c.setFillColor(colors.Color(0.9, 0.1, 0.2, alpha=0.12))
            c.translate(A4[0] / 2, A4[1] / 2)
            c.rotate(40)
            c.drawCentredString(0, 0, "DRAFT - NOT VALID")
            c.restoreState()

    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=1.8 * cm, bottomMargin=1.8 * cm, title=f"Prescription {p.id}")
    el = [Paragraph("<font color='#0d9488' size=18><b>RenalSight</b></font> &nbsp; Prescription and care plan", B), Spacer(1, 8)]
    snap = p.snapshot or {}
    el.append(Paragraph(f"<b>Patient:</b> {escape(patient.name)} &nbsp; <b>Age/Sex:</b> {snap.get('age', '-')}/{escape(str(snap.get('sex') or '-'))} &nbsp; "
                        f"<b>Rx no.:</b> {p.id} &nbsp; <b>Date:</b> {(p.signed_at or p.created_at):%d %b %Y}", B))
    el.append(Paragraph(f"<b>eGFR:</b> {snap.get('egfr', '-')} ({snap.get('g_stage', '-')}) &nbsp; <b>ACR:</b> {snap.get('acr', '-')} &nbsp; "
                        f"<b>K+:</b> {snap.get('potassium', '-')} &nbsp; <b>BP:</b> {snap.get('sbp', '-')}", B))
    el.append(Spacer(1, 10))
    rows = [["Medicine", "Dose", "Duration", "Instructions"]] + [[Paragraph(escape(str(c)), B) for c in r] for r in _lines(p, patient, doctor, items)]
    if len(rows) == 1:
        rows.append([Paragraph("No medicines prescribed (lifestyle plan only).", B), "", "", ""])
    t = Table(rows, colWidths=[4 * cm, 3.6 * cm, 2.6 * cm, 6.8 * cm], repeatRows=1)
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#ccfbf1")), ("GRID", (0, 0), (-1, -1), 0.4, colors.lightgrey), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    el += [t, Spacer(1, 10)]
    for name, lst in (p.care_plan or {}).get("sections", {}).items():
        if not lst or name == "urgent":
            continue
        el.append(Paragraph(f"<b>{name.replace('_', ' ').title()}</b>", B))
        for x in lst:
            el.append(Paragraph("&bull; " + escape(x["text_en"]), B))
        el.append(Spacer(1, 4))
    if p.doctor_notes:
        el.append(Paragraph("<b>Doctor's notes:</b> " + escape(p.doctor_notes), B))
    el.append(Spacer(1, 14))
    if signed and doctor:
        el.append(Paragraph(f"<b>Signed electronically by Dr. {escape(doctor.name)}</b> on {p.signed_at:%d %b %Y %H:%M} UTC", B))
    else:
        el.append(Paragraph("<font color='#e11d48'><b>This is a draft for doctor review. Do not take any medicine from it until it is signed.</b></font>", B))
    el.append(Spacer(1, 6))
    el.append(Paragraph("<font size=8 color='grey'>Generated by RenalSight, a learning/demo project and decision-support tool. It is not a medical device.</font>", B))
    doc.build(el, onFirstPage=mark, onLaterPages=mark)
    return buf.getvalue()


def build_html(p, patient, doctor, items, lang="en") -> str:
    snap = p.snapshot or {}
    meds = "".join(f"<tr><td>{escape(i.drug_name)}</td><td>{'' if i.dose_mg is None else f'{i.dose_mg:g} mg x {i.times_per_day:g}/day'}</td>"
                   f"<td>{i.duration_days or 'as directed'}</td><td>{escape(i.instructions or '')}</td></tr>" for i in items) or "<tr><td colspan=4>Lifestyle plan only</td></tr>"
    plan = "".join(f"<h3>{escape(n.replace('_', ' ').title())}</h3><ul>" + "".join(f"<li data-code='{escape(x['code'])}'>{escape(x['text_en'])}</li>" for x in l) + "</ul>"
                   for n, l in (p.care_plan or {}).get("sections", {}).items() if l and n != "urgent")
    sign = (f"<p><b>Signed electronically by Dr. {escape(doctor.name)}</b> on {p.signed_at:%d %b %Y %H:%M} UTC</p>" if p.status == "signed" and doctor
            else "<p style='color:#e11d48'><b>DRAFT - not valid until a doctor signs.</b></p>")
    return f"""<!doctype html><html lang="{escape(lang)}"><head><meta charset="utf-8"><title>Prescription {p.id}</title>
<style>body{{font-family:'Noto Sans','Noto Sans Tamil','Noto Sans Bengali','Noto Sans Telugu',system-ui,sans-serif;max-width:800px;margin:24px auto;color:#0f172a}}
h1{{color:#0d9488}}table{{width:100%;border-collapse:collapse}}td,th{{border:1px solid #cbd5e1;padding:6px;text-align:left}}th{{background:#ccfbf1}}</style></head><body>
<h1>RenalSight</h1><p><b>Patient:</b> {escape(patient.name)} | Age/Sex: {snap.get('age','-')}/{escape(str(snap.get('sex') or '-'))} | Rx {p.id}</p>
<p>eGFR {snap.get('egfr','-')} ({snap.get('g_stage','-')}) | ACR {snap.get('acr','-')} | K+ {snap.get('potassium','-')} | SBP {snap.get('sbp','-')}</p>
<table><tr><th>Medicine</th><th>Dose</th><th>Duration</th><th>Instructions</th></tr>{meds}</table>{plan}{sign}
<p style="color:#64748b;font-size:12px">Learning/demo project; decision support only.</p></body></html>"""
